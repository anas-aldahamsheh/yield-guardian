def fmt(e: dict, digits: int = 3) -> str:
    return f"{e['value']:.{digits}f} [{e['ci_low']:.{digits}f}, {e['ci_high']:.{digits}f}]"


def load(name: str) -> dict:
    return json.loads((REPORTS / name).read_text(encoding="utf-8"))


def choose_model() -> str:
    scores = {
        s: json.loads((RUNS / f"lot-seed{s}" / "history.json").read_text(encoding="utf-8"))["best"][
            "macro_f1"
        ]
        for s in SEEDS
    }
    return f"lot-seed{max(scores, key=scores.get)}"


def demo_wafers(out_dir) -> dict:
    lots = json.loads((PROCESSED / "demo" / "lots.json").read_text(encoding="utf-8"))
    table = pq.read_table(PARQUET, filters=pc.field("lot").isin(sorted(lots)))
    wafer_id = pc.binary_join_element_wise(
        table["lot"], pc.cast(table["wafer_index"], pa.string()), "-"
    )
    out = pa.table(
        {
            "wafer_id": wafer_id,
            "lot": table["lot"],
            "wafer_index": table["wafer_index"],
            "die_size": table["die_size"],
            "label": table["label"],
            "official_split": table["official_split"],
            "height": table["height"],
            "width": table["width"],
            "map": table["map"],
        }
    )
    pq.write_table(out, out_dir / "wafers.parquet", compression="zstd")
    shutil.copy(PROCESSED / "demo" / "lots.json", out_dir / "lots.json")
    return {"lots": len(lots), "wafers": out.num_rows}


