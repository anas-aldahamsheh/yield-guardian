def main() -> None:
    commit = git_commit()  # before this script rewrites the tracked model card
    deployed = choose_model()
    run = RUNS / deployed
    out = ARTIFACTS
    if out.exists():
        shutil.rmtree(out)
    (out / "demo").mkdir(parents=True)
    shutil.copy(run / "model.onnx", out / "model.onnx")
    shutil.copy(run / "ood_mahalanobis.npz", out / "ood_mahalanobis.npz")
    (out / "labels.json").write_text(
        json.dumps(CLASSES, indent=2) + "\n", encoding="utf-8", newline="\n"
    )
    (out / "preprocess.json").write_text(
        json.dumps(
            {
                "size": SIZE,
                "resize": "nearest",
                "channels": CHANNELS,
                "source_values": {"no_die": 0, "pass": 1, "fail": 2},
                "resize_rule": "output cell (i, j) samples source cell "
                "(min(floor((i + 0.5) * H / 64), H - 1), same for j with W)",
            },
            indent=2,
        )
        + "\n",
        encoding="utf-8",
        newline="\n",
    )
    shutil.copy(run / "calibration.json", out / "calibration.json")
    ood = json.loads((run / "ood.json").read_text(encoding="utf-8"))
    (out / "ood.json").write_text(
        json.dumps(
            {
                "method": "energy",
                "score": "-logsumexp(logits); higher is less familiar; flag when score > threshold",
                "threshold": ood["energy"]["threshold"],
                "in_distribution_recall": ood["energy"]["in_distribution_recall_validation"],
                "in_distribution_recall_test": ood["energy"]["in_distribution_recall_test"],
                "mahalanobis": {
                    **ood["mahalanobis"],
                    "parameters": "ood_mahalanobis.npz",
                    "score": "min over classes of (z - mean_c)^T precision (z - mean_c)",
                },
                "agreement_test": ood["agreement_test"],
                "test_share_flagged_by_class": ood["test_share_flagged_by_class"],
            },
            indent=2,
        )
        + "\n",
        encoding="utf-8",
        newline="\n",
    )

    metrics = {
        "git_commit": commit,
        "deployed_model": deployed,
        "splits": load("splits.json"),
        "lot_split": load("metrics_lot.json"),
        "official_split": load("metrics_official.json"),
        "leave_one_class_out": load("loco.json"),
        "similarity": {
            "lot": load("similarity_lot.json"),
            "official": load("similarity_official.json"),
        },
        "lot_excursions": load("lots.json"),
        "ood": ood,
        "onnx_parity": json.loads((run / "parity.json").read_text(encoding="utf-8")),
    }
    (out / "metrics.json").write_text(
        json.dumps(metrics, indent=2) + "\n", encoding="utf-8", newline="\n"
    )

    demo = demo_wafers(out / "demo")
    manifest_data = json.loads((REPO / "data" / "manifest.json").read_text(encoding="utf-8"))
    pickle_sha = next(
        f["sha256"] for f in manifest_data["wm811k"]["files"] if f["path"].endswith("LSWMD.pkl")
    )
    (out / "demo" / "ATTRIBUTION.md").write_text(
        ATTRIBUTION.format(pickle_sha=pickle_sha, **demo), encoding="utf-8", newline="\n"
    )

    card = model_card(metrics, deployed)
    (out / "model_card.md").write_text(card, encoding="utf-8", newline="\n")
    CARD.parent.mkdir(parents=True, exist_ok=True)
    CARD.write_text(card, encoding="utf-8", newline="\n")

    files = sorted(p for p in out.rglob("*") if p.is_file())
    data = [
        {"path": "data/raw/wm811k/LSWMD.pkl", "sha256": pickle_sha},
        {"path": "data/interim/wm811k/wm811k.parquet", "sha256": sha256(PARQUET)},
    ]
    env = environment()
    manifest = {
        "name": "wafermap",
        "version": "v1",
        "created_at": datetime.now(UTC).isoformat(timespec="seconds").replace("+00:00", "Z"),
        "git_commit": commit,
        "data": data,
        "environment": {
            "python": env["python"],
            "packages": env["packages"],
            "device": env["device"],
            "cuda": env["cuda"],
        },
        "files": [
            {"path": p.relative_to(out).as_posix(), "bytes": p.stat().st_size, "sha256": sha256(p)}
            for p in files
        ],
    }
    (out / "MANIFEST.json").write_text(
        json.dumps(manifest, indent=2) + "\n", encoding="utf-8", newline="\n"
    )
    print(json.dumps({"deployed": deployed, "files": len(files), **demo}))
    assert np.isfinite(metrics["lot_split"]["across_seeds"]["macro_f1"]["mean"])


if __name__ == "__main__":
    main()
