"""SYNTHETIC test data in the SECOM file format. For unit tests of mechanics only.

Nothing generated here is SECOM data, and none of it may appear in a report, a bundle
that is published, or anything a user sees. The files mimic the format (space-separated
readings with the literal ``NaN``, CRLF line endings, labels ``-1``/``1`` with quoted
day-first timestamps) so that the loader and the pipeline can be exercised end to end.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime, timedelta
from pathlib import Path

import numpy as np
import numpy.typing as npt

SYNTHETIC_NOTE = "SYNTHETIC data generated by tests/synthetic.py; not SECOM"


@dataclass(frozen=True)
class SyntheticSecom:
    """Arrays behind the files (labels as 0/1)."""

    features: npt.NDArray[np.float64]
    labels: npt.NDArray[np.int64]
    timestamps: list[datetime]


def make_synthetic(
    n_units: int = 400,
    n_features: int = 30,
    failure_rate: float = 0.15,
    seed: int = 7,
) -> SyntheticSecom:
    """SYNTHETIC units: two informative correlated pairs, noise, a constant and an empty
    column, a discrete column, scattered missing readings and some tied timestamps."""
    rng = np.random.default_rng(seed)
    X = rng.normal(size=(n_units, n_features))
    X[:, 1] = X[:, 0] + 0.1 * rng.normal(size=n_units)  # correlated pair
    X[:, 3] = X[:, 2] + 0.1 * rng.normal(size=n_units)
    logit = 1.4 * X[:, 0] - 1.1 * X[:, 2] + np.log(failure_rate / (1 - failure_rate)) - 0.6
    y = (rng.random(n_units) < 1.0 / (1.0 + np.exp(-logit))).astype(np.int64)
    X[:, 4] = 7.0  # constant
    X[:, 5] = np.nan  # never measured
    X[:, 6] = rng.integers(0, 3, size=n_units).astype(np.float64)  # discrete
    holes = rng.random(X.shape) < 0.03
    holes[:, 4] = False
    X[holes] = np.nan
    start = datetime(2008, 7, 19, 11, 55)
    steps = rng.integers(20, 240, size=n_units)
    steps[rng.random(n_units) < 0.05] = 0  # tied timestamps
    steps[0] = 0
    times = [start + timedelta(minutes=int(m)) for m in np.cumsum(steps)]
    return SyntheticSecom(features=X, labels=y, timestamps=times)


def write_secom_files(directory: Path, data: SyntheticSecom) -> Path:
    """Write ``secom.data`` and ``secom_labels.data`` (CRLF) into ``directory``."""
    directory.mkdir(parents=True, exist_ok=True)
    rows = []
    for row in data.features:
        rows.append(" ".join("NaN" if np.isnan(v) else repr(float(v)) for v in row))
    (directory / "secom.data").write_bytes(("\r\n".join(rows) + "\r\n").encode("ascii"))
    labels = []
    for label, ts in zip(data.labels, data.timestamps, strict=True):
        raw = 1 if label == 1 else -1
        labels.append(f'{raw} "{ts.strftime("%d/%m/%Y %H:%M:%S")}"')
    (directory / "secom_labels.data").write_bytes(("\r\n".join(labels) + "\r\n").encode("ascii"))
    (directory / "README.txt").write_text(SYNTHETIC_NOTE + "\n", encoding="utf-8")
    return directory
