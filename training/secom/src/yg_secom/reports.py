def limitations(metrics: dict[str, Any]) -> list[str]:
    blocks = {b["block"]: b for b in metrics["split"]["blocks"]["blocks"]}
    root = metrics["root_cause"]
    health = metrics["health"]
    items = [
        f"Few failures: the test block holds {blocks['test']['failures']} and the validation "
        f"block {blocks['validation']['failures']}, so every interval is wide and small "
        "differences between models are not distinguishable.",
        "The failure rate drifts over time (see eda.md: many failures early, fewer later); "
        "a model and calibrator fitted on earlier periods may not transfer to later ones.",
        "One fab, one product, about three months in 2008, anonymous sensors: results may not "
        "transfer to other tools, products or periods, and sensor meanings are unknown.",
        "The source timestamps have no time zone; they are stored as UTC without conversion.",
        "Associations, not causes: a sensor group linked to failure may be a proxy for "
        "another, unmeasured, factor.",
        "Validation-block risks come from rolling-origin fold models fitted on less data than "
        "the final model; they chose the settings and the calibrator, so their metrics are "
        "optimistic. The calibrator is fitted on fold-model scores and applied to the final "
        "model, an approximation the test block checks.",
        "Operating-point intervals are conditional on the thresholds chosen on the validation "
        "block; the variability of the threshold choice itself is not included.",
        "The test-block curve in operating_points.json is descriptive; choosing a new "
        "threshold from it and reporting test performance at that threshold would be "
        "optimistic.",
        "Reliability bins hold few failures each, so the observed rates are very uncertain.",
        f"{root['permutation_test']['power_note']}.",
        "Stability selection uses bootstrap resamples (not the half-samples of Meinshausen "
        "and Buehlmann), so their error bound does not apply; stability is descriptive.",
        "FDC has no drift labels in SECOM; alarms are judged only by their false-alarm rate "
        "on held-out in-control data and by association with failure. The PCA reference "
        "holds fewer units than sensors, so the covariance is estimated with few degrees of "
        "freedom.",
        "Sensor-health rules are deterministic and label-free; the jump test treats "
        "consecutive differences as independent, which a single spike violates.",
        "Missingness of sensor readings: "
        f"{len(health['missingness_associated_with_failure']['sensors'])} "
        "sensors associated with failure after Benjamini-Hochberg on the development period; "
        "reported as found, without searching for a test variant that would find more.",
    ]
    items += list(metrics.get("undefined_quantities", []))
    if not metrics["fdc"]["reference"]["stationary"]:
        items.append(
            "No candidate FDC reference passed the stationarity test; the shortest "
            "candidate is used."
        )
    if not metrics["calibration"]["lightgbm"]["converged"]:
        items.append("The Platt calibration fit did not converge.")
    return items


