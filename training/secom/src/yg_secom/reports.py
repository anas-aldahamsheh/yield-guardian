"""Markdown reports and figures generated from a pipeline run.

Every number in these documents is read from the run's own results (``metrics.json``
content and in-memory arrays); nothing is typed by hand.
"""

from __future__ import annotations

from pathlib import Path
from typing import TYPE_CHECKING, Any

import numpy as np
from yg_common.metrics import binary_curve

from yg_secom import figures

if TYPE_CHECKING:
    from yg_secom.pipeline import RunArtifacts

MODEL_NAMES = {
    "lightgbm": "LightGBM (main)",
    "logistic_regression": "L2 logistic regression",
    "balanced_random_forest": "Balanced random forest",
    "prevalence": "Prevalence (no skill)",
}


def provenance_line(commit: str, data_records: list[dict[str, Any]]) -> str:
    hashes = ", ".join(f"`{r['file']}` SHA-256 `{r['sha256'][:12]}...`" for r in data_records)
    return f"Generated by `yg_secom.pipeline` at commit `{commit[:12]}` from {hashes}."


def fmt(value: float | None, digits: int = 3) -> str:
    return "n/a" if value is None else f"{value:.{digits}f}"


def fmt_est(
    est: dict[str, Any] | None, digits: int = 3, pct: bool = False, pct_digits: int = 1
) -> str:
    if est is None or est.get("value") is None:
        return "n/a"
    scale = 100.0 if pct else 1.0
    unit = "%" if pct else ""
    d = pct_digits if pct else digits
    value = f"{scale * est['value']:.{d}f}{unit}"
    if est.get("ci_low") is None or est.get("ci_high") is None:
        return value
    return f"{value} ({scale * est['ci_low']:.{d}f} to {scale * est['ci_high']:.{d}f}{unit})"


def fmt_p(p: float | None) -> str:
    if p is None:
        return "n/a"
    return f"{p:.2g}" if p >= 0.001 else f"{p:.1e}"


