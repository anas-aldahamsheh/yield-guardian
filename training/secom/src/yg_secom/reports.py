def _blocks_table(metrics: dict[str, Any]) -> list[str]:
    rows = [
        "| Block | Role | Units | Failures | Failure rate | First unit | Last unit |",
        "|---|---|---|---|---|---|---|",
    ]
    roles = {
        "train": "rolling-origin warm-up: fitting only, no out-of-sample risk",
        "validation": "rolling-origin evaluation slices: out-of-fold risk; tuning, "
        "calibration, thresholds",
        "test": "untouched until the single final evaluation",
    }
    for b in metrics["split"]["blocks"]["blocks"]:
        rows.append(
            f"| {b['block']} | {roles[b['block']]} | {b['units']} | {b['failures']} | "
            f"{100 * b['failure_rate']:.1f}% | {b['first']} | {b['last']} |"
        )
    return rows


def _model_table(metrics: dict[str, Any], block: str) -> list[str]:
    rows = [
        "| Model | PR-AUC (95% CI) | ROC-AUC (95% CI) | Brier (95% CI) | ECE (95% CI) |",
        "|---|---|---|---|---|",
    ]
    for name, label in MODEL_NAMES.items():
        m = metrics["models"][name][block]
        rows.append(
            f"| {label} | {fmt_est(m['pr_auc'])} | {fmt_est(m['roc_auc'])} | "
            f"{fmt_est(m['brier'], 4)} | {fmt_est(m['ece'], 4)} |"
        )
    return rows


def _points_table(points: list[dict[str, Any]]) -> list[str]:
    rows = [
        "| Operating point | Threshold (risk) | Test false-alarm rate | Recall | Precision | "
        "False alarms per 100 units | TP | FP | TN | FN |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for p in points:
        rows.append(
            f"| {p['label']} (set on validation) | {p['threshold']:.4f} | "
            f"{fmt_est(p['fpr'], pct=True)} | {fmt_est(p['recall'], pct=True)} | "
            f"{fmt_est(p['precision'], pct=True)} | "
            f"{fmt_est(p['false_alarms_per_100'], 2)} | "
            f"{p['tp']} | {p['fp']} | {p['tn']} | {p['fn']} |"
        )
    return rows


def _groups_table(groups: dict[str, Any], limit: int = 20) -> list[str]:
    rows = [
        "| Group | Sensors | Representative | Importance | Stability | Permutation p | q | "
        "Significant | Strongest univariate member (q, direction) |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for g in groups["groups"][:limit]:
        tested = [u for u in g["univariate"] if u["q_value"] is not None]
        best = min(tested, key=lambda u: u["q_value"]) if tested else None
        uni = (
            (
                f"{best['sensor']} (q {fmt_p(best['q_value'])}, "
                f"{best['direction'].replace('_', ' ')})"
            )
            if best
            else "none tested"
        )
        members = ", ".join(g["sensors"][:6]) + (" ..." if len(g["sensors"]) > 6 else "")
        rows.append(
            f"| {g['group_id']} | {members} ({len(g['sensors'])}) | {g['representative']} | "
            f"{g['importance']:.4f} | {g['stability']:.2f} | {fmt_p(g['p_value'])} | "
            f"{fmt_p(g['q_value'])} | {'yes' if g['significant'] else 'no'} | {uni} |"
        )
    return rows


def _far_table(far: dict[str, Any]) -> list[str]:
    rows = [
        "| Limit | Statistic | Alarms / units | Rate (exact 95% CI) | Rate (day-clustered "
        "bootstrap 95% CI) |",
        "|---|---|---|---|---|",
    ]
    for level, entry in far.items():
        for stat in ("t2", "spe", "either"):
            r = entry[stat]
            rows.append(
                f"| {level}% | {stat.upper() if stat != 'either' else 'T2 or SPE'} | "
                f"{r['alarms']} / {r['units']} | {fmt_est(r['rate'], pct=True)} | "
                f"{fmt_est(r['rate_day_clustered'], pct=True)} |"
            )
    return rows


def results_markdown(
    metrics: dict[str, Any],
    art: RunArtifacts,
    eda: dict[str, Any],
    links: dict[str, str],
    provenance: str,
) -> str:
    main = metrics["models"]["lightgbm"]["test"]
    prevalence = metrics["models"]["prevalence"]["test"]["pr_auc"]
    points = metrics["operating_points"]["test"]
    default = points[0]
    split = metrics["split"]
    cv = split["cross_validation"]
    tuning = metrics["tuning"]
    calib = metrics["calibration"]
    root = metrics["root_cause"]
    fdc = metrics["fdc"]
    health = metrics["health"]
    comps = metrics["comparisons"]["pr_auc_difference"]
    plain = split["blocks"]["plain_60_20_20_for_comparison"]
    dev = split["blocks"]["development"]
    lines: list[str] = [
        "# SECOM results",
        "",
        provenance,
        "",
        "Every performance number below comes from units the scoring model never saw while it "
        "was fitted. The test block was evaluated once, after every choice was fixed; "
        "validation-block numbers are out-of-fold but were used to choose settings, so they "
        "are optimistic. Intervals are 95% intervals; the method is named in each table. "
        "Findings about sensors are statistical associations with failure, not causes.",
        "",
        "## Headline (test block)",
        "",
        "| Quantity | Value (95% CI) |",
        "|---|---|",
        f"| PR-AUC, LightGBM | {fmt_est(main['pr_auc'])} |",
        f"| PR-AUC, no skill (test failure rate) | {fmt_est(prevalence)} |",
        f"| ROC-AUC, LightGBM | {fmt_est(main['roc_auc'])} |",
        f"| Recall at the {default['label']} threshold (set on validation) | "
        f"{fmt_est(default['recall'], pct=True)} |",
        f"| Achieved test false-alarm rate at that threshold | "
        f"{fmt_est(default['fpr'], pct=True)} |",
        f"| False alarms per 100 units at that threshold | "
        f"{fmt_est(default['false_alarms_per_100'], 2)} |",
        f"| Stable sensor groups (sensors in them) | "
        f"{root['sensors_to_inspect']['stable_groups']} "
        f"({root['sensors_to_inspect']['sensors_in_stable_groups']} of "
        f"{root['sensors_to_inspect']['all_sensors']} model sensors) |",
        "",
        "## 1. Data and chronological split",
        "",
        f"{eda['counts']['units']} units, {eda['counts']['features']} sensors, "
        f"{eda['counts']['failures']} failures; see [eda.md](eda.md). Split rule: "
        f"{split['blocks']['rule']}.",
        "",
        *_blocks_table(metrics),
        "",
        f"Development period (train and validation blocks, every unit before the test "
        f"block): {dev['units']} units, {dev['failures']} failures, {dev['first']} to "
        f"{dev['last']}. Final models are refitted on all of it.",
        "",
        f"Why not a plain 60/20/20 split: it would give train {plain['units']['train']} units "
        f"({plain['failures']['train']} failures), validation {plain['units']['validation']} "
        f"({plain['failures']['validation']}) and test {plain['units']['test']} "
        f"({plain['failures']['test']}); {plain['why_not_used']}.",
        "",
    ]
    moves = split["blocks"]["moves"]
    lines.append(
        (
            "Boundary adjustments: "
            + "; ".join(
                f"{m['boundary']} moved {m['units_moved']} units ({m['reason']})" for m in moves
            )
            + "."
        )
        if moves
        else "No boundary adjustment was needed: every block held at least "
        f"{split['blocks']['min_failures_per_block']} failures."
    )
    lines += [
        "",
        f"Leakage check: {split['leakage_check']}.",
        "",
        f"Rolling-origin cross-validation: {cv['rule']}. Warm-up (train block): "
        f"{cv['warmup_units']} units ({cv['warmup_failures']} failures)"
        + (f"; merges: {'; '.join(cv['merges'])}" if cv["merges"] else "; no slice merged")
        + ".",
        "",
        "| Fold | Fitting units (failures) | Evaluation units (failures) | Evaluation period | "
        "LightGBM AP | Logistic AP | Random forest AP |",
        "|---|---|---|---|---|---|---|",
    ]
    fold_ap = tuning["fold_average_precision"]
    for i, f in enumerate(cv["folds"]):
        lines.append(
            f"| {f['fold']} | {f['train_units']} ({f['train_failures']}) | "
            f"{f['valid_units']} ({f['valid_failures']}) | {f['valid_first'][:16]} to "
            f"{f['valid_last'][:16]} | {fold_ap['lightgbm'][i]:.3f} | "
            f"{fold_ap['logistic_regression'][i]:.3f} | "
            f"{fold_ap['balanced_random_forest'][i]:.3f} |"
        )
    pre = metrics["preprocessing"]["development_period"]
    lines += [
        "",
        "## 2. Preprocessing (fitted on training rows only)",
        "",
        f"On the development period: {pre['kept_sensors']} sensors kept, {pre['dropped']} "
        f"dropped (constant or never measured there), {pre['missingness_indicators']} "
        f"missingness indicators added out of {pre['indicator_tests']} sensors tested "
        f"(Fisher's exact test, Benjamini-Hochberg q <= "
        f"{metrics['run']['config']['indicator_fdr']}; smallest q "
        f"{fmt_p(pre['smallest_indicator_q'])}), {pre['model_features']} model columns in "
        "total. Each fold repeats this on its own fitting rows: "
        + ", ".join(
            f"fold {p['fold']}: {p['model_features']} columns, "
            f"{p['missingness_indicators']} indicators"
            for p in metrics["preprocessing"]["per_fold"]
        )
        + ".",
        "",
        "## 3. Models and tuning",
        "",
        f"LightGBM: {tuning['lightgbm']['sampler']}; objective "
        f"{tuning['objective']}. Best mean fold average precision "
        f"{tuning['lightgbm']['best_mean_average_precision']:.3f} (optimistic, because these "
        "folds chose the parameters).",
        "",
        "| Hyperparameter | Search space | Chosen |",
        "|---|---|---|",
    ]
    for key, space in tuning["lightgbm"]["search_space"].items():
        value = tuning["lightgbm"]["best_params"].get(key)
        shown = f"{value:.4g}" if isinstance(value, float) else str(value)
        lines.append(f"| {key} | {space} | {shown} |")
    lines += [
        "",
        f"Fixed: class weight `scale_pos_weight` = passed/failed units in the fitting rows, "
        f"`deterministic=True`, `force_row_wise=True`, one thread, `max_bin` "
        f"{tuning['lightgbm']['fixed']['max_bin']}, seed {tuning['lightgbm']['fixed']['seed']}.",
        "",
        f"Logistic regression: {tuning['logistic_regression']['model']}; C chosen from "
        f"{tuning['logistic_regression']['grid']} by the same folds: C = "
        f"{tuning['logistic_regression']['best_C']:g} (mean fold average precision "
        f"{tuning['logistic_regression']['best_mean_average_precision']:.3f}).",
        "",
        f"Balanced random forest: {tuning['balanced_random_forest']['model']}, settings "
        f"{tuning['balanced_random_forest']['settings']}, not tuned.",
        "",
        "## 4. Test block (evaluated once)",
        "",
        *_model_table(metrics, "test"),
        "",
        "PR-AUC is average precision (step-function area, no interpolation); its no-skill "
        "value is the block's failure rate. Brier and ECE use Platt-calibrated "
        "probabilities (each model calibrated on its own pooled out-of-fold validation "
        f"scores). {calib['prevalence_baseline'].capitalize()}.",
        "",
        "Paired comparison of PR-AUC (LightGBM minus baseline), "
        f"{metrics['comparisons']['method']}:",
        "",
        "| Baseline | Difference (95% CI) | p-value |",
        "|---|---|---|",
    ]
    for name, c in comps.items():
        lines.append(
            f"| {MODEL_NAMES[name]} | {fmt_est(c['difference'])} | {fmt_p(c['p_value'])} |"
        )
    lines += [
        "",
        f"![Precision-recall]({links['pr_curve']})",
        "",
        f"![ROC]({links['roc_curve']})",
        "",
        f"![Risk over time]({links['risk_timeline']})",
        "",
        "## 5. Operating points",
        "",
        "Thresholds are set on the validation block (pooled out-of-fold calibrated risk: the "
        "smallest threshold whose false-alarm rate there is at most the target) and applied "
        "unchanged to the test block. Intervals are stratified bootstrap intervals "
        "conditional on the threshold.",
        "",
        *_points_table(points),
        "",
        "On the validation block (where the thresholds were set):",
        "",
        "| Operating point | Threshold | False-alarm rate | Recall | Precision | TP | FP | TN "
        "| FN |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
