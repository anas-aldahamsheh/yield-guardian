def result_figures(metrics: dict[str, Any], art: RunArtifacts, directory: Path) -> dict[str, Path]:
    out: dict[str, Path] = {}
    y = art.y_test
    prevalence = float(y.mean())
    series = [("lightgbm", 0), ("logistic_regression", 1), ("balanced_random_forest", 2)]

    fig, ax = figures.figure(5.6, 3.6)
    for name, slot in series:
        curve = binary_curve(y, art.test_scores[name].score)
        recall = np.r_[0.0, curve.recall]
        precision = np.r_[curve.precision[0], curve.precision]
        ap = metrics["models"][name]["test"]["pr_auc"]["value"]
        ax.step(
            recall,
            precision,
            where="post",
            color=figures.SERIES[slot],
            label=f"{MODEL_NAMES[name]}, PR-AUC {ap:.3f}",
        )
    ax.axhline(prevalence, color=figures.MUTED, linewidth=1.0)
    ax.annotate(
        f"prevalence {prevalence:.3f} (no skill)",
        (1.0, prevalence),
        xytext=(-4, 4),
        textcoords="offset points",
        ha="right",
        color=figures.INK_SECONDARY,
        fontsize=8,
    )
    ax.set_xlim(0, 1)
    ax.set_ylim(0, 1.02)
    ax.set_xlabel("recall (share of failed units flagged)")
    ax.set_ylabel("precision")
    ax.set_title("Precision-recall on the test block")
    ax.legend(loc="upper right")
    out["pr_curve"] = figures.save(fig, directory / "results_pr_curve.png")

    fig, ax = figures.figure(5.6, 3.6)
    for name, slot in series:
        curve = binary_curve(y, art.test_scores[name].score)
        auc = metrics["models"][name]["test"]["roc_auc"]["value"]
        ax.step(
            np.r_[0.0, curve.fpr],
            np.r_[0.0, curve.recall],
            where="post",
            color=figures.SERIES[slot],
            label=f"{MODEL_NAMES[name]}, ROC-AUC {auc:.3f}",
        )
    ax.plot([0, 1], [0, 1], color=figures.MUTED, linewidth=1.0)
    ax.set_xlabel("false-alarm rate")
    ax.set_ylabel("recall")
    ax.set_title("ROC on the test block")
    ax.legend(loc="lower right")
    out["roc_curve"] = figures.save(fig, directory / "results_roc_curve.png")

    fig, ax = figures.figure(5.0, 3.6)
    for key, label, slot in (
        ("test", "test block", 0),
        ("validation_in_sample", "validation, out-of-fold", 1),
    ):
        bins = metrics["calibration"][key]["reliability"]
        xs = np.array([b["mean_predicted"] for b in bins])
        ys = np.array([b["observed_rate"] for b in bins])
        lo = np.array([b["observed_ci_low"] for b in bins])
        hi = np.array([b["observed_ci_high"] for b in bins])
        ax.errorbar(
            xs,
            ys,
            yerr=[ys - lo, hi - ys],
            color=figures.SERIES[slot],
            marker="o",
            markersize=6,
            markeredgecolor=figures.SURFACE,
            markeredgewidth=1.5,
            capsize=0,
            elinewidth=1.0,
            linewidth=2.0,
            label=label,
        )
    top = max(0.05, float(ax.get_xlim()[1]), float(ax.get_ylim()[1]))
    ax.plot([0, top], [0, top], color=figures.MUTED, linewidth=1.0)
    ax.set_xlim(0, top)
    ax.set_ylim(0, min(1.0, top * 1.05))
    ax.set_xlabel("mean predicted risk in bin")
    ax.set_ylabel("observed failure rate in bin")
    ax.set_title("Reliability, equal-count bins, 95% Wilson intervals")
    ax.legend(loc="upper left")
    out["reliability"] = figures.save(fig, directory / "results_reliability.png")

    tl = art.timeline
    fig, ax = figures.figure(6.8, 3.2)
    has_risk = tl["risk"].notna()
    passed = has_risk & (tl["label"] == 0)
    failed = has_risk & (tl["label"] == 1)
    ax.scatter(
        tl.loc[passed, "timestamp"],
        tl.loc[passed, "risk"],
        s=8,
        color=figures.AXIS,
        label="passed",
        linewidths=0,
    )
    ax.scatter(
        tl.loc[failed, "timestamp"],
        tl.loc[failed, "risk"],
        s=26,
        color=figures.SERIES[1],
        edgecolors=figures.SURFACE,
        linewidths=1.0,
        label="failed",
    )
    for point in metrics["operating_points"]["test"][:1]:
        text = f"{point['label']} threshold"
        ax.axhline(point["threshold"], color=figures.INK_SECONDARY, linewidth=1.0)
        ax.annotate(
            text,
            (tl["timestamp"].iloc[-1], point["threshold"]),
            xytext=(-2, 3),
            textcoords="offset points",
            ha="right",
            fontsize=8,
            color=figures.INK_SECONDARY,
        )
    for block in ("validation", "test"):
        first = tl.loc[tl["block"] == block, "timestamp"].min()
        ax.axvline(first, color=figures.MUTED, linewidth=1.0)
        ax.annotate(
            f"{block} starts",
            (first, ax.get_ylim()[1]),
            xytext=(3, -10),
            textcoords="offset points",
            fontsize=8,
            color=figures.INK_SECONDARY,
        )
    ax.set_yscale("log")
    ax.set_ylabel("calibrated risk (log scale)")
    ax.set_title("Out-of-sample risk over time (train-block warm-up units have none)")
    ax.legend(loc="lower left")
    fig.autofmt_xdate()
    out["risk_timeline"] = figures.save(fig, directory / "results_risk_timeline.png")

    groups = art.groups["groups"][:20]
    threshold = art.groups["method"]["stability_threshold"]
    fig, ax = figures.figure(6.4, 4.6)
    ypos = np.arange(len(groups))[::-1]
    colours = [figures.SERIES[0] if g["stability"] >= threshold else figures.AXIS for g in groups]
    ax.barh(ypos, [g["importance"] for g in groups], height=0.6, color=colours)
    ax.set_yticks(
        ypos, [f"{g['group_id']} ({g['representative']}, {len(g['sensors'])})" for g in groups]
    )
    for yp, g in zip(ypos, groups, strict=True):
        ax.annotate(
            f"stability {g['stability']:.2f}",
            (g["importance"], yp),
            xytext=(3, -3),
            textcoords="offset points",
            fontsize=7,
            color=figures.INK_SECONDARY,
        )
    ax.set_xlabel("importance: sum of mean |SHAP| of members (log-odds)")
    ax.set_title(f"Top sensor groups (blue: stable, selected in >= {threshold:.0%} of refits)")
    ax.grid(axis="y", visible=False)
    out["group_importance"] = figures.save(fig, directory / "results_group_importance.png")

    fdc = metrics["fdc"]["model"]
    fig, axes = figures.figure(6.8, 4.6, nrows=2)
    for ax, stat, key in ((axes[0], "t2", "t2_limits"), (axes[1], "spe", "spe_limits")):
        ax.scatter(tl["timestamp"], tl[stat], s=6, color=figures.SERIES[0], linewidths=0)
        for level in ("99", "99.9"):
            ax.axhline(fdc[key][level], color=figures.INK_SECONDARY, linewidth=1.0)
            ax.annotate(
                f"{level}% limit",
                (tl["timestamp"].iloc[0], fdc[key][level]),
                xytext=(2, 3),
                textcoords="offset points",
                fontsize=7,
                color=figures.INK_SECONDARY,
            )
        ref = tl.loc[tl["fdc_period"] == "reference", "timestamp"]
        ax.axvspan(ref.min(), ref.max(), color=figures.SERIES[2], alpha=0.10, linewidth=0)
        ax.set_yscale("log")
        ax.set_ylabel("T²" if stat == "t2" else "SPE")
    axes[0].set_title("Hotelling T² and SPE per unit (shaded: reference fit period)")
    fig.autofmt_xdate()
    out["fdc"] = figures.save(fig, directory / "results_fdc.png")

    leading = art.fdc_series.get("leading", [])
    if leading:
        lg = leading[0]
        order_ts = tl["timestamp"]
        fig, ax = figures.figure(6.8, 2.8)
        ax.plot(order_ts, lg["series"]["ewma"], color=figures.SERIES[0], linewidth=1.5)
        for sign in (1, -1):
            ax.axhline(sign * lg["ewma_limit"], color=figures.INK_SECONDARY, linewidth=1.0)
        ax.set_ylabel("EWMA of group score")
        ax.set_title(f"EWMA chart, leading group {lg['group_id']} ({lg['representative']})")
        fig.autofmt_xdate()
        out["ewma"] = figures.save(fig, directory / "results_ewma.png")

    counts = metrics["health"]["status_counts"]
    fig, ax = figures.figure(5.0, 2.6)
    names = ["ok", "watch", "maintenance", "dead"]
    colours = [
        figures.STATUS["good"],
        figures.STATUS["warning"],
        figures.STATUS["serious"],
        figures.STATUS["critical"],
    ]
    ax.bar(names, [counts[n] for n in names], width=0.5, color=colours)
    for i, name in enumerate(names):
        ax.annotate(
            str(counts[name]),
            (i, counts[name]),
            xytext=(0, 3),
            textcoords="offset points",
            ha="center",
            fontsize=8,
            color=figures.INK_SECONDARY,
        )
    ax.set_ylabel("sensors")
    ax.set_title("Sensor health status")
    out["health"] = figures.save(fig, directory / "results_health.png")
    return out


